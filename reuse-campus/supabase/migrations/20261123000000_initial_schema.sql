-- =============================================================
-- ReUse Campus - PostgreSQL schema for Supabase
-- Port of database/schema.sql (MySQL) to Postgres.
-- MySQL ENUM -> VARCHAR + CHECK, AUTO_INCREMENT -> IDENTITY,
-- ON UPDATE CURRENT_TIMESTAMP -> trigger, FULLTEXT -> GIN tsvector.
-- =============================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- -------------------------------------------------------------
create table public.users (
  id                    bigint generated by default as identity primary key,
  full_name             varchar(120) not null,
  student_id            varchar(50) not null,
  email                 varchar(190) not null,
  password              varchar(255) not null,
  college               varchar(190),
  department            varchar(190),
  semester              varchar(30),
  phone                 varchar(30),
  profile_picture       varchar(255),
  contact_preferences   varchar(255) default 'email',
  bio                   text,
  email_verified        integer not null default 0 check (email_verified in (0,1)),
  verification_token    varchar(100),
  status                varchar(10) not null default 'active' check (status in ('active','suspended')),
  created_at            timestamp not null default now(),
  updated_at            timestamp not null default now(),
  constraint uq_users_email unique (email),
  constraint uq_users_student_id unique (student_id)
);
create index idx_users_status on public.users (status);
create trigger trg_users_updated before update on public.users
  for each row execute function public.set_updated_at();

-- -------------------------------------------------------------
create table public.admins (
  id         bigint generated by default as identity primary key,
  full_name  varchar(120) not null,
  username   varchar(80) not null,
  email      varchar(190) not null,
  password   varchar(255) not null,
  created_at timestamp not null default now(),
  constraint uq_admins_username unique (username),
  constraint uq_admins_email unique (email)
);

-- -------------------------------------------------------------
create table public.categories (
  id          bigint generated by default as identity primary key,
  name        varchar(100) not null,
  slug        varchar(120) not null,
  description varchar(255),
  icon        varchar(60),
  status      varchar(10) not null default 'active' check (status in ('active','inactive')),
  created_at  timestamp not null default now(),
  constraint uq_categories_slug unique (slug)
);

-- -------------------------------------------------------------
create table public.listings (
  id              bigint generated by default as identity primary key,
  user_id         bigint not null references public.users (id) on delete cascade,
  category_id     bigint not null references public.categories (id) on delete restrict,
  title           varchar(180) not null,
  description     text not null,
  item_condition  varchar(20) not null default 'good'
                    check (item_condition in ('new','like_new','good','fair')),
  exchange_type   varchar(20) not null
                    check (exchange_type in ('donation','borrow','exchange','sale')),
  price           numeric(10,2) default 0,
  availability    varchar(20) not null default 'available'
                    check (availability in ('available','reserved','completed')),
  pickup_location varchar(190),
  views           integer not null default 0,
  status          varchar(15) not null default 'active'
                    check (status in ('active','pending','removed','sold')),
  created_at      timestamp not null default now(),
  updated_at      timestamp not null default now()
);
create index idx_listings_user on public.listings (user_id);
create index idx_listings_category on public.listings (category_id);
create index idx_listings_status on public.listings (status);
create index idx_listings_type on public.listings (exchange_type);
create index idx_listings_created on public.listings (created_at);
create index ft_listings_search on public.listings
  using gin (to_tsvector('simple', coalesce(title,'') || ' ' || coalesce(description,'')));
create trigger trg_listings_updated before update on public.listings
  for each row execute function public.set_updated_at();

-- -------------------------------------------------------------
create table public.listing_images (
  id          bigint generated by default as identity primary key,
  listing_id  bigint not null references public.listings (id) on delete cascade,
  filename    varchar(255) not null,
  is_primary  integer not null default 0 check (is_primary in (0,1)),
  created_at  timestamp not null default now()
);
create index idx_images_listing on public.listing_images (listing_id);

-- -------------------------------------------------------------
create table public.item_requests (
  id                  bigint generated by default as identity primary key,
  listing_id          bigint not null references public.listings (id) on delete cascade,
  requester_id        bigint not null references public.users (id) on delete cascade,
  owner_id            bigint not null references public.users (id) on delete cascade,
  message             text,
  expected_return_date date,
  status              varchar(15) not null default 'pending'
                        check (status in ('pending','accepted','rejected','completed','cancelled')),
  return_confirmed    integer not null default 0 check (return_confirmed in (0,1)),
  created_at          timestamp not null default now(),
  updated_at          timestamp not null default now()
);
create index idx_req_listing on public.item_requests (listing_id);
create index idx_req_requester on public.item_requests (requester_id);
create index idx_req_owner on public.item_requests (owner_id);
create index idx_req_status on public.item_requests (status);
create trigger trg_requests_updated before update on public.item_requests
  for each row execute function public.set_updated_at();

-- -------------------------------------------------------------
create table public.favorites (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users (id) on delete cascade,
  listing_id bigint not null references public.listings (id) on delete cascade,
  created_at timestamp not null default now(),
  constraint uq_fav unique (user_id, listing_id)
);
create index idx_fav_listing on public.favorites (listing_id);

-- -------------------------------------------------------------
create table public.notifications (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users (id) on delete cascade,
  title      varchar(150) not null,
  message    varchar(500) not null,
  type       varchar(15) not null default 'system'
               check (type in ('request','system','exchange','report','account')),
  link       varchar(255),
  is_read    integer not null default 0 check (is_read in (0,1)),
  created_at timestamp not null default now()
);
create index idx_notif_user on public.notifications (user_id);
create index idx_notif_read on public.notifications (is_read);

-- -------------------------------------------------------------
create table public.contact_messages (
  id         bigint generated by default as identity primary key,
  name       varchar(120) not null,
  email      varchar(190) not null,
  subject    varchar(190) not null,
  message    text not null,
  user_id    bigint references public.users (id) on delete set null,
  is_read    integer not null default 0 check (is_read in (0,1)),
  created_at timestamp not null default now()
);
create index idx_contact_read on public.contact_messages (is_read);

-- -------------------------------------------------------------
create table public.reports (
  id              bigint generated by default as identity primary key,
  reporter_id     bigint not null references public.users (id) on delete cascade,
  listing_id      bigint references public.listings (id) on delete set null,
  reported_user_id bigint references public.users (id) on delete set null,
  reason          varchar(20) not null
                    check (reason in ('inappropriate','spam','misleading','other')),
  details         text,
  status          varchar(15) not null default 'pending'
                    check (status in ('pending','reviewed','resolved','dismissed')),
  admin_note      text,
  created_at      timestamp not null default now()
);
create index idx_reports_status on public.reports (status);
create index idx_reports_listing on public.reports (listing_id);

-- -------------------------------------------------------------
create table public.exchange_history (
  id            bigint generated by default as identity primary key,
  listing_id    bigint not null references public.listings (id) on delete cascade,
  requester_id  bigint not null references public.users (id) on delete cascade,
  owner_id      bigint not null references public.users (id) on delete cascade,
  exchange_type varchar(20) not null
                  check (exchange_type in ('donation','borrow','exchange','sale')),
  note          text,
  completed_at  timestamp not null default now()
);
create index idx_hist_requester on public.exchange_history (requester_id);
create index idx_hist_owner on public.exchange_history (owner_id);

-- -------------------------------------------------------------
create table public.reviews (
  id              bigint generated by default as identity primary key,
  listing_id      bigint not null references public.listings (id) on delete cascade,
  reviewer_id     bigint not null references public.users (id) on delete cascade,
  reviewed_user_id bigint not null references public.users (id) on delete cascade,
  rating          integer not null check (rating between 1 and 5),
  comment         text,
  created_at      timestamp not null default now(),
  constraint uq_review unique (listing_id, reviewer_id)
);

